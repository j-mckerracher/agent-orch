//! Secrets the process knows exactly, masked wherever they appear.
//!
//! Shape-based redaction cannot recognise a secret that is glued to other
//! text (`tok<value>`, `<value>-x`, two copies back to back) or wrapped across
//! lines. A registered secret is matched by value instead, ignoring ASCII case
//! and any ASCII whitespace or escaped line break (`\n`, `\r`, `\t`) between its
//! characters.
//!
//! The registry is process-global because redaction runs in places that have
//! no handle to the daemon: the panic hook, the host's log excerpts and test
//! failure output. Registered values live for the life of the process.

use crate::MASK;
use std::fs;
use std::path::PathBuf;
use std::sync::Mutex;
use std::time::SystemTime;

/// Values shorter than this are ignored: masking every occurrence of a short
/// string would destroy ordinary text.
const MIN_SECRET_LEN: usize = 8;

struct FileSource {
    path: PathBuf,
    /// Length and modification time of the contents last read.
    seen: Option<(u64, Option<SystemTime>)>,
}

struct Registry {
    values: Vec<String>,
    files: Vec<FileSource>,
}

static REGISTRY: Mutex<Registry> = Mutex::new(Registry {
    values: Vec::new(),
    files: Vec::new(),
});

fn registry() -> std::sync::MutexGuard<'static, Registry> {
    REGISTRY.lock().unwrap_or_else(|error| error.into_inner())
}

impl Registry {
    fn add(&mut self, value: &str) {
        let value = value.trim();
        let inside_mask = MASK.to_ascii_lowercase().contains(&value.to_ascii_lowercase());
        if value.len() < MIN_SECRET_LEN || inside_mask || self.values.iter().any(|v| v == value) {
            return;
        }
        self.values.push(value.to_owned());
    }

    /// Reads every watched file whose length or modification time changed.
    /// An unreadable or missing file keeps what it already contributed, so a
    /// token file removed at shutdown is still masked in the final log lines.
    fn refresh(&mut self) {
        let mut fresh = Vec::new();
        for source in &mut self.files {
            let Ok(meta) = fs::metadata(&source.path) else {
                continue;
            };
            let stamp = (meta.len(), meta.modified().ok());
            if source.seen == Some(stamp) {
                continue;
            }
            if let Ok(contents) = fs::read_to_string(&source.path) {
                source.seen = Some(stamp);
                fresh.push(contents);
            }
        }
        for contents in fresh {
            self.add(&contents);
        }
    }
}

/// Masks `value` by exact match in every later [`crate::redact`] call.
/// Values shorter than 8 characters are ignored.
pub fn register_secret(value: &str) {
    registry().add(value);
}

/// Masks the current and any later contents of the file at `path` (an IPC
/// token file) by exact match. The file is re-read when its length or
/// modification time changes, so a token regenerated by a daemon restart is
/// covered without the caller doing anything. A file that does not exist yet
/// is picked up once it appears.
pub fn watch_secret_file(path: impl Into<PathBuf>) {
    let path = path.into();
    let mut registry = registry();
    if !registry.files.iter().any(|source| source.path == path) {
        registry.files.push(FileSource { path, seen: None });
    }
    registry.refresh();
}

pub(crate) fn mask_registered(input: &str) -> String {
    let secrets = {
        let mut registry = registry();
        registry.refresh();
        registry.values.clone()
    };
    secrets
        .iter()
        .fold(input.to_owned(), |text, secret| mask_one(&text, secret))
}

fn mask_one(input: &str, secret: &str) -> String {
    let (hay, needle) = (input.as_bytes(), secret.as_bytes());
    let mut out = String::with_capacity(input.len());
    let (mut copied, mut i) = (0, 0);
    while i < hay.len() {
        if hay[i].eq_ignore_ascii_case(&needle[0]) {
            if let Some(end) = match_at(hay, i, needle) {
                out.push_str(&input[copied..i]);
                out.push_str(MASK);
                copied = end;
                i = end;
                continue;
            }
        }
        i += 1;
    }
    out.push_str(&input[copied..]);
    out
}

/// End of the match of `needle` starting at `start`, allowing separators
/// between its bytes. Matches begin and end on the needle's own bytes, which
/// are whole characters because `needle` is valid UTF-8.
fn match_at(hay: &[u8], start: usize, needle: &[u8]) -> Option<usize> {
    let mut at = start;
    for (index, want) in needle.iter().enumerate() {
        loop {
            if at < hay.len() && hay[at].eq_ignore_ascii_case(want) {
                at += 1;
                break;
            }
            let skip = if index == 0 { 0 } else { separator_len(&hay[at.min(hay.len())..]) };
            if skip == 0 {
                return None;
            }
            at += skip;
        }
    }
    Some(at)
}

fn separator_len(rest: &[u8]) -> usize {
    match rest {
        [byte, ..] if byte.is_ascii_whitespace() => 1,
        [b'\\', b'n' | b'r' | b't', ..] => 2,
        _ => 0,
    }
}
